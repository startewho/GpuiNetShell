namespace GpuiNetShell.Elements;

/// <summary>Scroll axis: 0 is vertical, 1 is horizontal.</summary>
public enum ScrollAxis : uint
{
    Vertical = 0,
    Horizontal = 1,
}

/// <summary>Resizable axis: 0 is a row, 1 is a column.</summary>
public enum ResizeAxis : uint
{
    Horizontal = 0,
    Vertical = 1,
}
